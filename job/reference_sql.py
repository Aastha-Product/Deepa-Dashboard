"""Generate the reference-data migration from the seed CSVs, so the database matches them exactly.

    python -m job.reference_sql > supabase/migrations/<timestamp>_reference_data.sql
"""
import csv

from job import config


def _q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _rows(name):
    with open(config.DATA_DIR / "seed" / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def build() -> str:
    out = ["-- P2: reference data from Case 01 seed files (generated by job/reference_sql.py). Safe to re-run.", ""]

    dist = _rows("distributors.csv")
    out.append("INSERT INTO distributors (distributor_id, distributor_name, region, status) VALUES")
    out.append(",\n".join(f"  ({_q(r['Distributor_ID'])}, {_q(r['Distributor_Name'])}, {_q(r['Region'])}, {_q(r['Status'])})"
                          for r in dist))
    out.append("ON CONFLICT (distributor_id) DO UPDATE SET distributor_name = EXCLUDED.distributor_name,"
               " region = EXCLUDED.region, status = EXCLUDED.status;\n")

    skus = _rows("sku_master.csv")
    out.append("INSERT INTO sku_master (sku_id, sku_name, category, perishability, standard_reorder_qty,"
               " unit_of_measure, distributor_id) VALUES")
    out.append(",\n".join(
        f"  ({_q(r['SKU_ID'])}, {_q(r['SKU_Name'])}, {_q(r['Category'])}, {_q(r['Perishability'])}, "
        f"{int(r['Standard_Reorder_Qty'])}, {_q(r['Unit_of_Measure'])}, {_q(r['Distributor_ID'])})" for r in skus))
    out.append("ON CONFLICT (sku_id) DO UPDATE SET sku_name = EXCLUDED.sku_name, category = EXCLUDED.category,"
               " perishability = EXCLUDED.perishability, standard_reorder_qty = EXCLUDED.standard_reorder_qty,"
               " unit_of_measure = EXCLUDED.unit_of_measure, distributor_id = EXCLUDED.distributor_id;\n")

    cal = _rows("festival_calendar.csv")
    out.append("INSERT INTO festival_calendar (year_month, year, month, is_festival) VALUES")
    out.append(",\n".join(
        f"  ({_q(r['Year_Month'])}, {int(r['Year'])}, {int(r['Month'])}, "
        f"{'true' if r['Is_Festival_Month'].strip().upper() == 'TRUE' else 'false'})" for r in cal))
    out.append("ON CONFLICT (year_month) DO UPDATE SET is_festival = EXCLUDED.is_festival;")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    print(build(), end="")
